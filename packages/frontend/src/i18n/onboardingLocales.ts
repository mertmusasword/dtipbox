const dicts: Record<string, Dict> = { tr, en, de, fr, es, ar, zh, pt, id, ja, ru };

/** Returns a translator for onboarding strings with {placeholder} interpolation. */
export function useOnboardingText() {
  const { language } = useLanguage();
  const dict = dicts[language as string] || en;
  return (key: OnboardingKey, vars?: Record<string, string | number>): string => {
    let s = dict[key] ?? en[key] ?? key;
    if (vars) for (const k of Object.keys(vars)) s = s.split(`{${k}}`).join(String(vars[k]));
    return s;
  };
}
