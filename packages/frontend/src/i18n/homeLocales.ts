export function getHomeText(key: keyof typeof homeTranslations, lang: SupportedLanguage, params?: Record<string, string | number>): string {
  const entry = homeTranslations[key];
  if (!entry) return key as string;
  let str = entry[lang] || entry['en'] || entry['tr'] || (key as string);
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    });
  }
  return str;
}
